pub const Options = struct {
    builder: *std.Build,
    profile: *someday.Profile,
    path: someday.PackagePath,
    build_name: []const u8,
};
pub const CacheVariableValue = struct {
    pub const Type = enum {
        bool,
        filepath,
        path,
        string,
        internal,
        pub fn toString(self: Type) []const u8 {
            return switch (self) {
                .bool => "BOOL",
                .filepath => "FILEPATH",
                .path => "PATH",
                .string => "STRING",
                .internal => "INTERNAL",
            };
        }
    };
    value: []const u8,
    type: Type,
    docstring: []const u8 = "[generated by someday]",
    force: bool = false,
};

cmd_cache: *std.Build.Step.WriteFile = undefined,
profile: *someday.Profile,
cmd_gen: *std.Build.Step.Run,
cmd_build: *std.Build.Step.Run,
cmd_install: *std.Build.Step.Run,

cache: StringArrayHashMap(CacheVariableValue),

include_path: std.Build.LazyPath,
library_path: std.Build.LazyPath,
step: *std.Build.Step,

pub fn init(options: Options) !CMakePackage {
    var arena = ArenaAllocator.init(options.profile.config.gpa);
    defer arena.deinit();
    const alloc = arena.allocator();

    var cache = StringArrayHashMap(CacheVariableValue).init(options.profile.config.arena.allocator());

    const buildgen = if (options.profile.usage.cmake == .system) options.profile.config.someday_builder.addSystemCommand(&.{"cmake"}) else options.profile.config.addRunCMake();
    buildgen.addArg("-GNinja"); // it's advised by cmake documentation to specify the generator using -G command line option.
    buildgen.addArg("-S");
    switch (options.path) {
        .absolute => |abs| buildgen.addArg(abs),
        .lazy_path => |lazy| buildgen.addDirectoryArg(lazy),
    }
    const build_dir = buildgen.addPrefixedOutputDirectoryArg("-B", try allocPrint(alloc, "{s}-build", .{options.build_name}));
    const install_dir = buildgen.addPrefixedOutputDirectoryArg("-DCMAKE_INSTALL_PREFIX=", options.build_name);
    if (options.profile.usage.toolchain == .zig) {
        // TODO: learn how to write a toolchain configuration file
        try cache.put("CMAKE_AR", .{
            .type = .path,
            .value = options.profile.config.zig_tool_paths.ar,
            .force = true,
        });
        try cache.put("CMAKE_C_COMPILER", .{
            .type = .path,
            .value = options.profile.config.zig_tool_paths.cc,
            .force = true,
        });
        try cache.put("CMAKE_CXX_COMPILER", .{
            .type = .path,
            .value = options.profile.config.zig_tool_paths.@"c++",
            .force = true,
        });
        try cache.put("CMAKE_OBJCOPY", .{
            .type = .path,
            .value = options.profile.config.zig_tool_paths.objcopy,
            .force = true,
        });
        try cache.put("CMAKE_RANLIB", .{
            .type = .path,
            .value = options.profile.config.zig_tool_paths.ranlib,
            .force = true,
        });
        try cache.put("CMAKE_RC_COMPILER", .{
            .type = .path,
            .value = options.profile.config.zig_tool_paths.rc,
            .force = true,
        });
        try cache.put("CMAKE_C_LINKER_DEPFILE_SUPPORTED", .{ .type = .bool, .value = "OFF" });
        try cache.put("CMAKE_CXX_LINKER_DEPFILE_SUPPORTED", .{ .type = .bool, .value = "OFF" });
    }

    const run_build = if (options.profile.usage.ninja == .system) options.profile.config.someday_builder.addSystemCommand(&.{"ninja"}) else options.profile.config.addRunNinja();
    if (options.profile.parallel_jobs) |n| {
        run_build.addArg(try allocPrint(alloc, "-j{d}", .{n}));
    }
    run_build.setCwd(build_dir);

    const install = if (options.profile.usage.ninja == .system) options.profile.config.someday_builder.addSystemCommand(&.{"ninja"}) else options.profile.config.addRunNinja();
    install.addArg("install");
    if (options.profile.parallel_jobs) |n| {
        install.addArg(try allocPrint(alloc, "-j{d}", .{n}));
    }
    install.setCwd(build_dir);

    run_build.step.dependOn(&buildgen.step);
    install.step.dependOn(&run_build.step);

    return CMakePackage{
        .cmd_gen = buildgen,
        .cmd_build = run_build,
        .cmd_install = install,

        .cache = cache,
        .profile = options.profile,

        .include_path = install_dir.path(options.builder, "include"),
        .library_path = install_dir.path(options.builder, "lib"),
        .step = &install.step,
    };
}

pub fn build(self: *CMakePackage) void {
    buildInternal(self) catch |err| if (err == error.OutOfMemory) @panic("OOM") else @panic("unknown error when building a someday package!");
}

fn buildInternal(self: *CMakePackage) !void {
    var arena = ArenaAllocator.init(self.profile.config.gpa);
    defer arena.deinit();
    const alloc = arena.allocator();

    var iter = self.cache.iterator();
    var cache = try ArrayList([]const u8).initCapacity(alloc, self.cache.keys().len);
    while (iter.next()) |entry| {
        const force_string: []const u8 = if (entry.value_ptr.force) "FORCE" else "";
        const value_string: []const u8 = if (entry.value_ptr.type == .bool) entry.value_ptr.value else try allocPrint(alloc, "\"{s}\"", .{entry.value_ptr.value});

        try cache.append(try allocPrint(
            alloc,
            "set({s} {s} CACHE {s} \"{s}\" {s})\n",
            .{ entry.key_ptr.*, value_string, entry.value_ptr.type.toString(), entry.value_ptr.docstring, force_string },
        ));
    }

    const content = try std.mem.concat(alloc, u8, try cache.toOwnedSlice());
    const write_cache = self.profile.config.someday_builder.addWriteFile("cache.cmake", content);
    self.cmd_cache = write_cache;
    self.cmd_gen.step.dependOn(&write_cache.step);
    self.cmd_gen.addArg("-C");
    self.cmd_gen.addFileArg(write_cache.getDirectory().path(self.profile.config.someday_builder, "cache.cmake"));
    if (self.profile.usage.ninja != .system) {
        self.cmd_gen.step.dependOn(self.profile.config.ninja_step);
        self.cmd_gen.addArg(try allocPrint(alloc, "-DCMAKE_MAKE_PROGRAM={s}", .{self.profile.config.ninja_path}));
    }
}

const ArrayList = std.ArrayList;
const StringArrayHashMap = std.StringArrayHashMap;
const Allocator = std.mem.Allocator;
const ArenaAllocator = std.heap.ArenaAllocator;
const path = std.fs.path;
const CMakePackage = @This();
const allocPrint = std.fmt.allocPrint;
const std = @import("std");
const someday = @import("../core.zig");
